<?php

declare(strict_types=1);

namespace App\Service\DocumentGenerator\Report\Section;

use App\Service\DocumentGenerator\DocStyleRegistry;
use App\Service\DocumentGenerator\Report\ReportContext;
use App\Service\DocumentGenerator\Report\SectionBuilderInterface;
use PhpOffice\PhpWord\Element\Section;
use PhpOffice\PhpWord\Style\ListItem;

/**
 * Раздел «Основные расчётные положения» — стандартный текст.
 */
final class CalculationBasisSection implements SectionBuilderInterface
{
    public function build(Section $section, ReportContext $context): void
    {
        $body = DocStyleRegistry::bodyText();
        $para = DocStyleRegistry::paragraphIndent();

        $paragraphs = [
            'Расчеты конструкций антенной опоры выполнены в соответствии с требованиями СП 63.13330.2018 «Бетонные и железобетонные конструкции», СП 20.13330.2016 «Нагрузки и воздействия» и СП 52-102-2004 «Предварительно напряженные железобетонные конструкции».',

            'Расчеты проведены по первому (прочности) и по второму (трещиностойкости) предельным состояниям. По первому предельному состоянию расчеты проведены на расчетные нагрузки, по второму - на нормативные нагрузки.',

            'При расчете конструкций столб учитывались следующие нагрузки:',
            '1. Постоянные и временные длительные:',
            ['- собственный вес конструкций опоры и технологического оборудования;'],
            '2. Кратковременные:',
            ['- ветровое воздействие (статическое и динамическое);', '- гололедная нагрузка;'],
            '3. Особые:',
            ['- сейсмическая нагрузка.'],

            'Ветровая нагрузка на антенное оборудование и трубостойки принята с учетом следующих параметров:',
            [
                '- изменения азимутов панельных антенн до 30˚ в процессе эксплуатации/модернизации, в соответствии с требованиями операторов сотовой связи;',
                '- ориентации антенн РРЛ в соответствии с расчетным направлением ветрового потока;',
                '- расположения радиоблоков/радиомодулей «стеком» и «кейсами».',
            ],

            'Величины кратковременных и особых нагрузок определялись в соответствии с климатическими условиями места расположения объекта согласно требованиям СП 131.13330.2012 «Строительная климатология», СП 20.13330.2016 «Нагрузки и воздействия» и СП 14.13330.2018 «Строительство в сейсмических районах».',

//            'Пульсационная составляющая ветровой нагрузки учитывается в программном комплексе «ЛИРА-САПР» автоматически.',

            'Аэродинамические коэффициенты, принятые при расчете ветровых нагрузок, рассчитывались согласно СП 20.13330.2016 «Нагрузки и воздействия» (Приложение В).',

            'При расчетах учитывается уровень ответственности сооружения. Уровень ответственности – второй (нормальный), принят в соответствии с документом №384-ФЗ «Технический регламент о безопасности зданий и сооружений» от 30 декабря 2009 г.',

            'Расчет выполнен с использованием программного комплекса «ЛИРА-САПР». Программный комплекс (ПК) «ЛИРА-САПР» предназначен для автоматизированного расчета и проектирования строительных и машиностроительных конструкций, а также для проверки несущей способности, подбора и проверки сечений стрежневых металлических элементов в соответствии с СП 16.13330.2017 «Стальные конструкции».',

            'При расчете были приняты следующие коэффициенты надежности:',
            [
                '- для собственного веса конструкций и оборудования 1.05',
                '- по ответственности 1.0 ',
            ],
        ];

        foreach ($paragraphs as $paragraph) {
            if (is_array($paragraph)) {
                foreach ($paragraph as $item) {
                    $section->addText($item, $body, $para);
                }
                continue;
            }
            $section->addText($paragraph, $body, $para);
        }
    }
}
